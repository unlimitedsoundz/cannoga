export const ALL_PUBLICATIONS: Publication[] = [
    CANNOGA_VIEWBOOK_2026_2027
];

export function getPublicationBySlug(slug?: string): Publication {
    if (!slug) return CANNOGA_VIEWBOOK_2026_2027;
    const cleanSlug = slug.toLowerCase().trim();
    const found = ALL_PUBLICATIONS.find(p => p.slug.toLowerCase() === cleanSlug);
    return found || CANNOGA_VIEWBOOK_2026_2027;
}

export function searchPublication(publication: Publication, query: string): SearchResult[] {
    if (!query || query.trim().length < 2) return [];
    const q = query.toLowerCase().trim();
    const results: SearchResult[] = [];

    publication.pages.forEach(page => {
        const text = (page.fullText || '') + ' ' + page.title + ' ' + page.section + ' ' + (page.subtitle || '');
        const lowerText = text.toLowerCase();
        
        if (lowerText.includes(q)) {
            // Count occurrences
            const regex = new RegExp(q.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'gi');
            const matches = text.match(regex);
            const matchesCount = matches ? matches.length : 1;

            // Generate contextual snippet
            const idx = lowerText.indexOf(q);
            const start = Math.max(0, idx - 40);
            const end = Math.min(text.length, idx + q.length + 80);
            let snippet = text.substring(start, end).trim();
            if (start > 0) snippet = '...' + snippet;
            if (end < text.length) snippet = snippet + '...';

            results.push({
                pageNumber: page.pageNumber,
                pageTitle: page.title,
                section: page.section,
                snippet,
                matchesCount
            });
        }
    });

    return results;
}
